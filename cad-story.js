const ASSEMBLY_FRAMES = 9;
const assemblyFrameCache = { cover: [], shaft: [] };
for (const mode of ['cover', 'shaft']) {
  for (let i = 0; i < ASSEMBLY_FRAMES; i++) {
    const src = `assets/renders/assembly/${mode}_${String(i).padStart(2, '0')}.jpg`;
    assemblyFrameCache[mode].push(src);
    const img = new Image();
    img.src = src;
  }
}

const storyRange = document.querySelector('#assembly-progress');
const storyImg = document.querySelector('#assembly-frame-img');
const storyHud = document.querySelector('#assembly-hud');
let storyOrder = 'cover', storyTimer = null;

function updateAssembly() {
  if (!storyRange) return;
  const p = Number(storyRange.value);
  const cover = storyOrder === 'cover';
  const frameIdx = Math.min(ASSEMBLY_FRAMES - 1, Math.round((p / 100) * (ASSEMBLY_FRAMES - 1)));
  if (storyImg) {
    const nextSrc = assemblyFrameCache[storyOrder][frameIdx];
    if (storyImg.getAttribute('src') !== nextSrc) storyImg.setAttribute('src', nextSrc);
  }
  if (storyHud) {
    const zVal = Math.round(70 - 62 * (cover ? p / 100 : Math.min(1, (p / 100) / 0.55)));
    const stateTag = cover
      ? (p >= 35 ? 'INTERSECTION · 201.06 mm³' : `APPROACH · z = ${zVal} mm`)
      : (p <= 55 ? `SHAFT INSERT · z = ${zVal} mm` : 'COVER INSTALL · 0.00 mm³');
    storyHud.textContent = stateTag;
    storyHud.dataset.conflict = String(cover && p >= 35);
  }
  document.querySelector('#assembly-output').textContent = p + '%';
  const resEl = document.querySelector('#assembly-result');
  resEl.textContent = cover ? '201.06 mm³' : '0.00 mm³';
  resEl.dataset.clear = String(!cover);
  document.querySelector('#assembly-result-title').textContent = extra[locale].swept;
  document.querySelector('#assembly-result-text').textContent = extra[locale][cover ? 'coverResult' : 'shaftResult'];
  document.querySelector('#assembly-play').textContent = extra[locale][storyTimer ? 'assemblyPause' : 'assemblyPlay'];
}

function stopAssembly() {
  if (storyTimer) { clearInterval(storyTimer); storyTimer = null; }
}

for (const order of ['cover', 'shaft']) {
  document.querySelector('#order-' + order)?.addEventListener('click', () => {
    stopAssembly();
    storyOrder = order;
    storyRange.value = order === 'cover' ? 50 : 75;
    for (const o of ['cover', 'shaft']) document.querySelector('#order-' + o)?.setAttribute('aria-pressed', String(o === order));
    updateAssembly();
  });
}

storyRange?.addEventListener('input', () => { stopAssembly(); updateAssembly(); });
document.querySelector('#assembly-play')?.addEventListener('click', () => {
  if (storyTimer) { stopAssembly(); updateAssembly(); return; }
  if (Number(storyRange.value) >= 100) storyRange.value = 0;
  storyTimer = setInterval(() => {
    const next = Math.min(100, Number(storyRange.value) + 2);
    storyRange.value = next;
    if (next >= 100) stopAssembly();
    updateAssembly();
  }, 55);
  updateAssembly();
});

const storySetLocale = setLocale;
setLocale = function(lang) { storySetLocale(lang); updateAssembly(); };
